#!/bin/sh
# Print the Homebrew formula for a release.
#
#   packaging/homebrew/formula.sh <version> <download url> <dir with the archives>
#
# The archives are the ones packaging/archive.sh builds, one per target. The
# formula installs those prebuilt binaries, so installing needs no Rust
# toolchain. KITH_REPO is the GitHub repository the formula links to (default
# CarterCole/kith).
set -eu

if [ $# -ne 3 ]; then
	sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'
	exit 2
fi
version=$1 url=$2 dir=$3
repo=${KITH_REPO:-CarterCole/kith}

sha() {
	f="$dir/kith-$version-$1.tar.gz"
	[ -f "$f" ] || { echo "missing $f" >&2; exit 1; }
	shasum -a 256 "$f" | cut -d' ' -f1
}
darwin_arm64=$(sha aarch64-apple-darwin)
darwin_amd64=$(sha x86_64-apple-darwin)
linux_arm64=$(sha aarch64-unknown-linux-gnu)
linux_amd64=$(sha x86_64-unknown-linux-gnu)

cat <<EOF
# Generated by packaging/homebrew/formula.sh for kith $version. Do not edit.
class Kith < Formula
  desc "Universal identity: one root, many devices, sessions, aliases and delegation"
  homepage "https://github.com/$repo"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$url/kith-$version-aarch64-apple-darwin.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$url/kith-$version-x86_64-apple-darwin.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$url/kith-$version-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$url/kith-$version-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install "kith"
  end

  def caveats
    <<~EOS
      Kith is a draft spec with a reference implementation, not production ready:
        https://github.com/$repo#layout

      State lives in ~/.kith (or \$KITH_HOME). On macOS, private keys go to the
      login keychain and this device's key into the Secure Enclave; the keychain
      items name the binary that made them, so after an upgrade macOS asks once
      per item ("Always Allow" remembers). On Linux the keys sit in plaintext in
      identity.json (mode 0600), the only backend there.

      Start with a hub (yours, or one you were invited to):
        kith init --hub https://hub.example
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/kith --version")

    # A hub needs no configuration: start one, create an identity with its keys
    # in a file (no keychain in the sandbox) and publish it there.
    port = free_port
    hub = "http://localhost:#{port}"
    home = testpath/"home"
    pid = spawn bin/"kith", "hub", "serve", "--addr", "127.0.0.1:#{port}",
                "--data", testpath/"hub", "--beacon", "none"
    begin
      jwks = ""
      20.times do
        sleep 0.5
        jwks = Utils.popen_read("curl", "-sf", "#{hub}/.well-known/jwks.json")
        break if jwks.include?("keys")
      end
      assert_match "keys", jwks

      did = shell_output("#{bin}/kith --home #{home} init --keystore file --hub #{hub}").strip
      assert_match "did:kith:", did
      system bin/"kith", "--home", home, "publish"
      assert_match did, shell_output("#{bin}/kith --home #{home} status")
      assert_match(/\A\s*\[\s*\{/, shell_output("curl -sf #{hub}/v1/kel/#{did}"))
    ensure
      Process.kill "TERM", pid
      Process.wait pid
    end
  end
end
EOF
